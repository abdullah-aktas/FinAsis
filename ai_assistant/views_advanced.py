@login_required
@require_POST
def api_analyze_sentiment(request):
    """API: Sentiment analizi"""
    try:
        data = json.loads(request.body)
        text = data.get("text", "")

        if not text:
            return JsonResponse({"error": "Text required"}, status=400)

        result = SentimentAnalysisService.analyze_text(text)
        return JsonResponse(result)

    except Exception as e:
        return JsonResponse({"error": str(e)}, status=500)


@login_required
@require_POST
def api_summarize_text(request):
    """API: Doküman özetleme"""
    try:
        data = json.loads(request.body)
        text = data.get("text", "")
        max_sentences = data.get("max_sentences", 5)

        if not text:
            return JsonResponse({"error": "Text required"}, status=400)

        result = DocumentSummarizationService.summarize_text(text, max_sentences)
        return JsonResponse(result)

    except Exception as e:
        return JsonResponse({"error": str(e)}, status=500)


@login_required
@require_POST
def api_generate_report(request):
    """API: Otomatik rapor üret"""
    try:
        data = json.loads(request.body)
        report_type = data.get("report_type")

        if report_type == "daily_summary":
            report = AutoReportGenerationService.generate_daily_summary(request.user)
        elif report_type == "monthly_financial":
            report = AutoReportGenerationService.generate_monthly_financial(
                request.user
            )
        else:
            return JsonResponse({"error": "Invalid report type"}, status=400)

        return JsonResponse(
            {
                "id": report.id,
                "title": report.title,
                "status": report.status,
                "summary": report.summary,
            }
        )

    except Exception as e:
        return JsonResponse({"error": str(e)}, status=500)
