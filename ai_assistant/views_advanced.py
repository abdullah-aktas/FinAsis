@login_required
def sentiment_analyze(request):
    """Sentiment analizi sayfası"""
    if request.method == "POST":
        text = request.POST.get("text", "")
        source_type = request.POST.get("source_type", "document")

        if text:
            sentiment = SentimentAnalysisService.analyze_and_save(
                text=text, user=request.user, source_type=source_type
            )
            return redirect("ai_assistant:sentiment_detail", pk=sentiment.id)

    # Son analizler
    recent_analyses = SentimentAnalysis.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:10]

    return render(
        request,
        "ai_assistant/sentiment_analyze.html",
        {
            "recent_analyses": recent_analyses,
            "source_types": SentimentAnalysis.SOURCE_TYPES,
        },
    )


@login_required
def sentiment_list(request):
    """Sentiment analiz listesi"""
    analyses = SentimentAnalysis.objects.filter(user=request.user).order_by(
        "-created_at"
    )

    # Filtreleme
    sentiment_filter = request.GET.get("sentiment")
    source_filter = request.GET.get("source")

    if sentiment_filter:
        analyses = analyses.filter(sentiment=sentiment_filter)
    if source_filter:
        analyses = analyses.filter(source_type=source_filter)

    return render(
        request,
        "ai_assistant/sentiment_list.html",
        {
            "analyses": analyses[:200],
            "sentiment_choices": SentimentAnalysis.SENTIMENT_CHOICES,
            "source_types": SentimentAnalysis.SOURCE_TYPES,
            "selected_sentiment": sentiment_filter,
            "selected_source": source_filter,
        },
    )


@login_required
def sentiment_detail(request, pk):
    """Sentiment analiz detayı"""
    analysis = get_object_or_404(SentimentAnalysis, pk=pk, user=request.user)
    return render(request, "ai_assistant/sentiment_detail.html", {"analysis": analysis})


