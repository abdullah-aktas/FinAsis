@login_required
def analytics_dashboard(request):
    """
    Gelişmiş analitik dashboard - tüm AI özellikleri bir arada
    """
    # İstatistikler
    sentiment_count = SentimentAnalysis.objects.filter(user=request.user).count()
    summary_count = DocumentSummary.objects.filter(user=request.user).count()
    report_count = AutoGeneratedReport.objects.filter(user=request.user).count()
    analytics_count = AdvancedAnalytics.objects.filter(user=request.user).count()

    # Son analizler
    recent_sentiments = SentimentAnalysis.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:5]
    recent_summaries = DocumentSummary.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:5]
    recent_reports = AutoGeneratedReport.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:5]
    recent_analytics = AdvancedAnalytics.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:5]

    # Sentiment dağılımı
    sentiment_dist = (
        SentimentAnalysis.objects.filter(user=request.user)
        .values("sentiment")
        .annotate(count=Count("id"))
    )
    sentiment_data = {item["sentiment"]: item["count"] for item in sentiment_dist}

    context = {
        "sentiment_count": sentiment_count,
        "summary_count": summary_count,
        "report_count": report_count,
        "analytics_count": analytics_count,
        "recent_sentiments": recent_sentiments,
        "recent_summaries": recent_summaries,
        "recent_reports": recent_reports,
        "recent_analytics": recent_analytics,
        "sentiment_data": json.dumps(sentiment_data),
    }

    return render(request, "ai_assistant/analytics_dashboard.html", context)


