@login_required
def run_analytics(request):
    """Gelişmiş analitik çalıştır"""
    if request.method == "POST":
        analytics_type = request.POST.get("analytics_type")

        if analytics_type == "revenue_forecast":
            days = int(request.POST.get("forecast_days", 30))
            analytics = AdvancedAnalyticsService.revenue_forecast(request.user, days)
        elif analytics_type == "customer_segmentation":
            analytics = AdvancedAnalyticsService.customer_segmentation(request.user)
        elif analytics_type == "abc_analysis":
            analytics = AdvancedAnalyticsService.abc_analysis(request.user)
        else:
            return JsonResponse({"error": "Invalid analytics type"}, status=400)

        return redirect("ai_assistant:analytics_detail", pk=analytics.id)

    return render(
        request,
        "ai_assistant/run_analytics.html",
        {"analytics_types": AdvancedAnalytics.ANALYTICS_TYPES},
    )


