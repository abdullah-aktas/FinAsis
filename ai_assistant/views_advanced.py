    # Son özetler
    recent_summaries = DocumentSummary.objects.filter(user=request.user).order_by(
        "-created_at"
    )[:10]

    return render(
        request,
        "ai_assistant/summarize_document.html",
        {
            "recent_summaries": recent_summaries,
            "document_types": DocumentSummary.DOCUMENT_TYPES,
        },
    )


