@login_required
def auto_reports(request):
    """Otomatik rapor yönetimi"""
    reports = AutoGeneratedReport.objects.filter(user=request.user).order_by(
        "-created_at"
    )

    # Filtreleme
    report_type = request.GET.get("type")
    status = request.GET.get("status")

    if report_type:
        reports = reports.filter(report_type=report_type)
    if status:
        reports = reports.filter(status=status)

    return render(
        request,
        "ai_assistant/auto_reports.html",
        {
            "reports": reports[:100],
            "report_types": AutoGeneratedReport.REPORT_TYPES,
            "statuses": AutoGeneratedReport.STATUS_CHOICES,
            "selected_type": report_type,
            "selected_status": status,
        },
    )


@login_required
def generate_report(request):
    """Yeni rapor oluştur"""
    if request.method == "POST":
        report_type = request.POST.get("report_type")

        if report_type == "daily_summary":
            report = AutoReportGenerationService.generate_daily_summary(request.user)
        elif report_type == "monthly_financial":
            report = AutoReportGenerationService.generate_monthly_financial(
                request.user
            )
        elif report_type == "expense_analysis":
            days = int(request.POST.get("days", 30))
            report = AutoReportGenerationService.generate_expense_analysis(
                request.user, days
            )
        else:
            return JsonResponse({"error": "Invalid report type"}, status=400)

        return redirect("ai_assistant:report_detail", pk=report.id)

    return render(
        request,
        "ai_assistant/generate_report.html",
        {"report_types": AutoGeneratedReport.REPORT_TYPES},
    )


@login_required
def report_detail(request, pk):
    """Rapor detayı"""
    report = get_object_or_404(AutoGeneratedReport, pk=pk, user=request.user)
    return render(request, "ai_assistant/report_detail.html", {"report": report})


